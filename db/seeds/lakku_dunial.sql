SELECT NULL, 'seed.lakku_dunial', 'source', 'lakku_dunial',
  jsonb_build_object('records', (SELECT COUNT(*) FROM seed_ld),
                     'stale', (SELECT COUNT(*) FROM seed_ld_stale));

